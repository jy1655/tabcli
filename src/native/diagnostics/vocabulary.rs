//! Public doctor identifiers and reasons. Add words here before using them in a check.

macro_rules! vocabulary {
    ($kind:ident { $($constant:ident => $name:literal,)* }) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub(in crate::native) struct $kind(&'static str);

        impl $kind {
            $(pub(in crate::native) const $constant: Self = Self($name);)*

            pub(in crate::native) const ALL: &'static [Self] = &[$(Self::$constant,)*];

            pub(in crate::native) const fn name(self) -> &'static str {
                self.0
            }
        }
    };
}

